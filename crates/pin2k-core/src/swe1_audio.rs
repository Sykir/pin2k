/// Resolves an `ard_*` descriptor to a deterministic DCS `SoundId` using `selector`.
pub fn resolve_ard(name: &str, selector: usize) -> Option<SoundId> {
    let idx = SWE1_ARD_POOLS.binary_search_by_key(&name, |p| p.name).ok()?;
    let ids = SWE1_ARD_POOLS[idx].ids;
    (!ids.is_empty()).then(|| SoundId(ids[selector % ids.len()]))
}

/// Resolves an `acd_*` command name to a DCS `SoundId` using `selector`.
pub fn resolve_acd(name: &str, selector: usize) -> Option<SoundId> {
    let idx = SWE1_ACD_SOUNDS.binary_search_by_key(&name, |p| p.name).ok()?;
    let ids = SWE1_ACD_SOUNDS[idx].ids;
    (!ids.is_empty()).then(|| SoundId(ids[selector % ids.len()]))
}

/// Returns total number of available SWE1 `ARD` audio pools.
pub const fn ard_count() -> usize {
    SWE1_ARD_POOLS.len()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ard_pools_are_sorted_and_cover_rom_descriptors() {
        assert!(SWE1_ARD_POOLS.len() >= 300);
        for w in SWE1_ARD_POOLS.windows(2) {
            assert!(w[0].name < w[1].name, "unsorted ARD: {} >= {}", w[0].name, w[1].name);
        }
        for w in SWE1_ACD_SOUNDS.windows(2) {
            assert!(w[0].name < w[1].name, "unsorted ACD: {} >= {}", w[0].name, w[1].name);
        }
        let mut uniq = std::collections::HashSet::new();
        for p in SWE1_ARD_POOLS {
            for &id in p.ids {
                uniq.insert(id);
            }
        }
        assert!(uniq.len() >= 250, "expected >= 250 unique DCS IDs in ARD pools, got {}", uniq.len());
        for key in [
            "ard_attract_mode_flipper_sounds",
            "ard_ball_saved",
            "ard_battle_droid_scene_complete",
            "ard_tilt_warning_speech",
            "ard_extra_ball_fanfare",
            "ard_bonus_countdown",
        ] {
            assert!(resolve_ard(key, 0).is_some(), "missing {key}");
        }
    }
}
